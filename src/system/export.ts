import { TECHNOLOGIES } from "./catalog";
import { KIND_LABEL, type ComponentKind, type SystemComponent, type SystemDesign } from "./model";

/** The software system the project's containers live in, in the Structurizr workspace. */
const SYSTEM_ID = "project";

/** Words either format reads as syntax, so no component may use them as its identifier. */
const RESERVED = [SYSTEM_ID, "end", "graph", "flowchart", "subgraph", "style", "class", "click", "workspace", "model", "views", "container", "softwareSystem", "person", "group"];

/** Identifiers both formats accept: letters, digits and underscores, starting with a letter, never a keyword. */
function identifiers(design: SystemDesign): Map<string, string> {
  const taken = new Set<string>(RESERVED);
  const ids = new Map<string, string>();
  for (const component of design.components) {
    const base = `${/^[a-z]/i.test(component.name) ? "" : "c_"}${component.name.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "")}` || "component";
    let id = base;
    for (let counter = 2; taken.has(id); counter += 1) id = `${base}_${counter}`;
    taken.add(id);
    ids.set(component.id, id);
  }
  return ids;
}

function idOf(ids: Map<string, string>, componentId: string): string {
  const id = ids.get(componentId);
  if (id === undefined) throw new Error(`Connection to a component that is not in the design: ${componentId}`);
  return id;
}

function technologyLabel(component: SystemComponent): string {
  return TECHNOLOGIES.find((technology) => technology.id === component.technology)?.label ?? component.technology ?? "";
}

