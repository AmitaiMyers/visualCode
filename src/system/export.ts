const MERMAID_SHAPE: Record<ComponentKind, [string, string]> = {
  frontend: ["[/", "/]"],
  service: ["[", "]"],
  worker: ["[[", "]]"],
  database: ["[(", ")]"],
  cache: ["[(", ")]"],
  queue: [">", "]"],
  storage: ["[(", ")]"],
  external: ["((", "))"],
};

function mermaidText(text: string): string {
  return text.replace(/"/g, "#quot;");
}

/** A Mermaid flowchart, left to right: frontends, then services, then what they use. */
export function toMermaid(design: SystemDesign): string {
  const ids = identifiers(design);
  const nodes = design.components.map((component) => {
    const [open, close] = MERMAID_SHAPE[component.kind];
    const technology = technologyLabel(component);
    const label = technology === "" ? `${component.name}<br/><i>${KIND_LABEL[component.kind]}</i>` : `${component.name}<br/><i>${KIND_LABEL[component.kind]} · ${technology}</i>`;
    return `  ${idOf(ids, component.id)}${open}"${mermaidText(label)}"${close}`;
  });
  const edges = design.connections.map((connection) => `  ${idOf(ids, connection.from)} -->|"${mermaidText(connection.label)}"| ${idOf(ids, connection.to)}`);
  return ["flowchart LR", ...nodes, ...edges].join("\n") + "\n";
}

// ---------------------------------------------------------------------------

const STRUCTURIZR_TAG: Partial<Record<ComponentKind, string>> = {
  frontend: "Frontend",
  database: "Database",
  cache: "Database",
  storage: "Database",
  queue: "Queue",
};

function quoted(text: string): string {
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/**
 * A Structurizr DSL workspace (C4 model): the project as one software system whose containers are the
 * apps and data stores, external hosts as separate software systems, and a container view.
 */
export function toStructurizr(design: SystemDesign, projectName: string): string {
  const ids = identifiers(design);
  const containers = design.components.filter((component) => component.kind !== "external");
  const externals = design.components.filter((component) => component.kind === "external");

  const element = (component: SystemComponent, keyword: "container" | "softwareSystem", indent: string): string[] => {
    const args = keyword === "container" ? [component.name, KIND_LABEL[component.kind], technologyLabel(component)] : [component.name, KIND_LABEL[component.kind]];
    const tag = keyword === "container" ? STRUCTURIZR_TAG[component.kind] : "External";
    const head = `${indent}${idOf(ids, component.id)} = ${keyword} ${args.map(quoted).join(" ")}`;
    return tag === undefined ? [head] : [`${head} {`, `${indent}    tags ${quoted(tag)}`, `${indent}}`];
  };

  return [
    `workspace ${quoted(projectName)} ${quoted("System design generated by VisualCode")} {`,
    "    model {",
    `        ${SYSTEM_ID} = softwareSystem ${quoted(projectName)} {`,
    ...containers.flatMap((component) => element(component, "container", "            ")),
    "        }",
    ...externals.flatMap((component) => element(component, "softwareSystem", "        ")),
    ...design.connections.map((connection) => `        ${idOf(ids, connection.from)} -> ${idOf(ids, connection.to)} ${quoted(connection.label)}`),
    "    }",
    "    views {",
    `        container ${SYSTEM_ID} ${quoted("Containers")} {`,
    "            include *",
    "            autolayout lr",
    "        }",
    "        styles {",
    `            element ${quoted("Database")} {`,
    "                shape Cylinder",
    "            }",
    `            element ${quoted("Queue")} {`,
    "                shape Pipe",
    "            }",
    `            element ${quoted("Frontend")} {`,
    "                shape WebBrowser",
    "            }",
    `            element ${quoted("External")} {`,
    "                background #999999",
    "            }",
    "        }",
    "    }",
    "}",
    "",
  ].join("\n");
}
